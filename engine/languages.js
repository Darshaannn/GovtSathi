  class LanguageRegistry {
    static getAll() {
      return LANGUAGES;
    }

    static get(code) {
      if (!code) return LANGUAGES[0];
      const match = LANGUAGES.find(l => l.code.toLowerCase() === code.toLowerCase());
      return match || LANGUAGES[0];
    }

    static isReviewed(code) {
      const lang = LanguageRegistry.get(code);
      return !!lang.reviewed;
    }

    static getString(key, langCode) {
      const dict = UI_STRINGS[key];
      if (!dict) return '';
      if (dict[langCode]) return dict[langCode];
      return dict.en || '';
    }
  }

  window.GovGuideLanguages = {
    LANGUAGES,
    UI_STRINGS,
    LanguageRegistry
  };
